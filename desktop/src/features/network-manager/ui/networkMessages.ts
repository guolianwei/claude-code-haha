import type { TranslationKey } from '@/i18n'

export function networkIssueKey(code: string): TranslationKey | null {
  if (['TCP_CONNECTED', 'DIRECT_HTTP_RESPONSE', 'EXPLICIT_PROXY_HTTP_RESPONSE'].includes(code)) return 'networkManager.vpnRouteProbeSuccess'
  if (['TCP_TIMEOUT', 'TCP_UNREACHABLE', 'DIRECT_HTTP_FAILED', 'EXPLICIT_PROXY_FAILED'].includes(code)) return 'networkManager.vpnRouteProbeFailed'
  if (['EXPECTED_ROUTE_SELECTED', 'PHYSICAL_CONNECTED', 'VPN_CONNECTED', 'RELAY_READY', 'WIREGUARD_AUTHENTICATED_PATH'].includes(code)) return 'networkManager.recovery.yes'
  if (code === 'ROUTE_MISMATCH') return 'networkManager.path.notSelected'
  if (code === 'PHYSICAL_UNAVAILABLE') return 'networkManager.recovery.hostFix'
  if (code === 'VPN_UNAVAILABLE') return 'networkManager.recovery.vpnFix'
  if (code === 'PROXY_CONFIGURATION_MISMATCH') return 'networkManager.recovery.proxyFix'
  if (code === 'TRANSPORT_READINESS_TIMEOUT') return 'networkManager.recovery.transportTimeout'
  if (code === 'BUSINESS_NOT_VERIFIED') return 'networkManager.recovery.businessUnverified'
  if (code === 'PROXY_NOT_VERIFIED') return 'networkManager.recovery.proxyUnverified'
  if (code.includes('INSPECTION_UNKNOWN') || code.includes('COLLECTION_FAILED')) return 'networkManager.recovery.collectionUnknown'
  if (code === 'RELAY_NOT_READY') return 'networkManager.recovery.relayFix'
  if (code === 'RELAY_TASK_MISSING') return 'networkManager.recovery.taskFix'
  if (code.startsWith('TUNNEL_NO_HANDSHAKE')) return 'networkManager.recovery.tunnelFix'
  if (code.includes('VPN_AMBIGUOUS')) return 'networkManager.steps.vpnAmbiguous'
  if (code === 'VPN_RECONNECT_REQUIRED') return 'networkManager.steps.vpnReconnectRequired'
  if (code.startsWith('RELAY_BINARY_')) return 'networkManager.recovery.relayHint'
  if (code.includes('RELAY_TASK_DEFINITION')) return 'networkManager.steps.relayDefinitionMismatch'
  if (['PLAN_STALE', 'PLAN_EXPIRED', 'FIELD_CHANGED', 'PROXY_CONFIG_CHANGED'].includes(code)) return 'networkManager.errorPlan'
  if (['INVALID_NETWORK_PROFILE', 'NETWORK_CONFIG_INVALID', 'NETWORK_CONFIG_LIMIT', 'PROFILE_LIMIT'].includes(code)) return 'networkManager.errorProfile'
  if (code === 'REVISION_CONFLICT') return 'networkManager.errorRevision'
  if (code.startsWith('PROXY_')) return 'networkManager.errorProxy'
  if (code.startsWith('SAKURA_')) return 'networkManager.errorLogin'
  if (code.includes('RECOVERY')) return 'networkManager.errorRecovery'
  if (code === 'MANAGEMENT_UNREACHABLE') return 'networkManager.errorManagement'
  if (code.includes('SOURCE_ACL') || code.startsWith('RELAY_UNREACHABLE')) return 'networkManager.errorAcl'
  if (code === 'NETWORK_BUSY') return 'networkManager.errorBusy'
  if (['HOST_NOT_FOUND', 'INVALID_HOST_ID'].includes(code)) return 'networkManager.errorHost'
  if (code === 'WINDOWS_REQUIRED') return 'networkManager.unsupported'
  return null
}
